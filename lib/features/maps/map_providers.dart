/// Where positions come from; tests override it with a fake.
final locationSourceProvider = Provider<LocationSource>(
  (ref) => const GeolocatorSource(),
);

/// Asks for location permission the first time it is read (the
/// navigation screen), never at startup.
final locationAccessProvider = FutureProvider<LocationAccess>(
  (ref) => ref.watch(locationSourceProvider).request(),
);

/// Continuous GPS fixes while the navigation screen is open; empty until
/// access is granted.
final positionProvider = StreamProvider<Fix>((ref) {
  final access = ref.watch(locationAccessProvider).value;
  if (access != LocationAccess.granted) return const Stream.empty();
  return ref.watch(locationSourceProvider).fixes();
});
